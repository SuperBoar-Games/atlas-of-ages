"""Wikidata helper: list candidate ids for names, and fetch coordinates and dates for linked places and entries."""
import argparse
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

from rdflib import RDF, Graph, Namespace
from rdflib.namespace import SKOS

ROOT = Path(__file__).resolve().parent.parent
AOA = Namespace('https://w3id.org/atlas-of-ages#')
WD = 'http://www.wikidata.org/entity/'
API = 'https://www.wikidata.org/w/api.php'
SPARQL = 'https://query.wikidata.org/sparql'
AGENT = 'atlas-of-ages/0.1 (https://github.com/SuperBoar-Games/atlas-of-ages)'
OUT = ROOT / 'graph' / 'wikidata.ttl'


def get(url, params, tries=5):
    req = urllib.request.Request(f'{url}?{urllib.parse.urlencode(params)}', headers={'User-Agent': AGENT, 'Accept': 'application/json'})
    for attempt in range(tries):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code not in (429, 500, 502, 503, 504) or attempt == tries - 1:
                raise
            time.sleep(int(e.headers.get('Retry-After', 0)) or 2 ** attempt)
        except (TimeoutError, urllib.error.URLError):
            if attempt == tries - 1:
                raise
            time.sleep(2 ** attempt)


def rows(template, qids, chunk=25):
    """Run a SPARQL template over the ids in small batches; the public endpoint times out on large VALUES lists."""
    qids = list(qids)
    for i in range(0, len(qids), chunk):
        values = ' '.join(f'wd:{q}' for q in qids[i:i + chunk])
        yield from get(SPARQL, {'query': template % values, 'format': 'json'})['results']['bindings']
        time.sleep(0.5)


def search(names, limit, with_coords):
    for name in names:
        hits = get(API, {'action': 'wbsearchentities', 'search': name, 'language': 'en', 'limit': limit, 'format': 'json'})['search']
        ids = [h['id'] for h in hits]
        coords = {}
        if ids and with_coords:
            q = 'SELECT ?i ?c WHERE { VALUES ?i { %s } ?i wdt:P625 ?c }' % ' '.join(f'wd:{i}' for i in ids)
            for b in get(SPARQL, {'query': q, 'format': 'json'})['results']['bindings']:
                coords[b['i']['value'].rsplit('/', 1)[1]] = b['c']['value']
        print(f'## {name}')
        for h in hits:
            print(f"  {h['id']:<11} {h.get('label', ''):<28} {coords.get(h['id'], ''):<32} {h.get('description', '')}")
        time.sleep(0.3)


def linked(graph, cls):
    # closeMatch carries traditional identifications (Kishkindha with the Hampi area); their coordinates serve too.
    for s in graph.subjects(RDF.type, cls):
        for m in [*graph.objects(s, SKOS.exactMatch), *graph.objects(s, SKOS.closeMatch)]:
            if str(m).startswith(WD):
                yield s, str(m)[len(WD):]
                break


def year(value):
    # Wikidata times look like "-0322-01-01T00:00:00Z"; keep the signed year.
    sign = '-' if value.startswith('-') else ''
    return f"{sign}{value.lstrip('+-').split('-')[0].zfill(4)}"


def fetch():
    g = Graph()
    for f in sorted((ROOT / 'graph').glob('*.ttl')):
        if f != OUT:
            g.parse(f)
    places = dict(linked(g, AOA.Place))
    entries = {s: q for cls in (AOA.Person, AOA.Sage, AOA.Deva, AOA.Avatar, AOA.Event, AOA.Story, AOA.Polity) for s, q in linked(g, cls)}
    lines = ['# Generated by tools/wikidata.py fetch; do not edit. Coordinates (P625) and dates from Wikidata.', '',
             '@prefix : <https://w3id.org/atlas-of-ages#> .',
             '@prefix aoa: <https://w3id.org/atlas-of-ages#> .', '@prefix geo: <http://www.opengis.net/ont/geosparql#> .',
             '@prefix time: <http://www.w3.org/2006/time#> .', '@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .',
             '@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .', '@prefix dcterms: <http://purl.org/dc/terms/> .',
             '@prefix schema: <https://schema.org/> .', '@prefix skos: <http://www.w3.org/2004/02/skos/core#> .', '']
    local = lambda s: str(s).replace(str(AOA), ':')
    cite =lambda q: f'dcterms:source [ a aoa:Citation ; rdfs:label "Wikidata {q}" ; schema:url <https://www.wikidata.org/wiki/{q}> ]'

    if places:
        found, names = {}, {}
        q = 'SELECT ?i ?c ?n WHERE { VALUES ?i { %s } ?i wdt:P625 ?c . OPTIONAL { ?i rdfs:label ?n FILTER(LANG(?n) = "en") } }'
        for b in rows(q, set(places.values())):
            qid = b['i']['value'].rsplit('/', 1)[1]
            found.setdefault(qid, b['c']['value'])
            if 'n' in b:
                names.setdefault(qid, b['n']['value'])
        for s, qid in sorted(places.items(), key=lambda kv: str(kv[0])):
            if qid not in found:
                print(f'no coordinates on Wikidata: {local(s)} ({qid})', file=sys.stderr)
                continue
            name = f' ;\n    aoa:modernName "{names[qid].replace(chr(34), "")}"' if qid in names else ''
            lines.append(f'{local(s)} geo:hasGeometry [ geo:asWKT "{found[qid]}"^^geo:wktLiteral ]{name} ;\n    {cite(qid)} .\n')

    if entries:
        # Start: birth, start time, inception, point in time. End: death, end time, dissolved.
        q = '''SELECT ?i ?p ?t WHERE { VALUES ?i { %s } VALUES ?p { wdt:P569 wdt:P580 wdt:P571 wdt:P585 wdt:P570 wdt:P582 wdt:P576 }
               ?i ?p ?t . FILTER(DATATYPE(?t) = xsd:dateTime) }'''
        dates = {}
        for b in rows(q, set(entries.values())):
            dates.setdefault(b['i']['value'].rsplit('/', 1)[1], {}).setdefault(b['p']['value'].rsplit('/', 1)[1], b['t']['value'])
        for s, qid in sorted(entries.items(), key=lambda kv: str(kv[0])):
            if (s, AOA.when, None) in g:
                continue
            d = dates.get(qid, {})
            begin = next((d[p] for p in ('P569', 'P580', 'P571', 'P585') if p in d), None)
            end = next((d[p] for p in ('P570', 'P582', 'P576', 'P585') if p in d), None)
            if not begin and not end:
                print(f'no dates on Wikidata: {local(s)} ({qid})', file=sys.stderr)
                continue
            parts = []
            if begin:
                parts.append(f'time:hasBeginning [ a time:Instant ; time:inXSDgYear "{year(begin)}"^^xsd:gYear ]')
            if end:
                parts.append(f'time:hasEnd [ a time:Instant ; time:inXSDgYear "{year(end)}"^^xsd:gYear ]')
            lines.append(f"{local(s)} aoa:when [ a time:Interval ;\n        {' ;\n        '.join(parts)} ] ;\n    {cite(qid)} .\n")

    # Places of birth (P19) and death (P20) become attestations. A place already in the graph under the same Wikidata
    # item is reused; others are added as established places. A hand-written attestation of the same kind wins.
    people = {s: q for s, q in entries.items() if (s, RDF.type, AOA.Polity) not in g}
    if people:
        known = {}
        # An exact match wins over a traditional identification: Hampi is Vijayanagara before it is Kishkindha.
        for match in (SKOS.exactMatch, SKOS.closeMatch):
            for s, m in g.subject_objects(match):
                if (s, RDF.type, AOA.Place) in g and str(m).startswith(WD):
                    known.setdefault(str(m)[len(WD):], local(s))
        have = {(local(g.value(a, AOA.who)), str(g.value(a, AOA.does)).rsplit('-', 1)[1]) for a in g.subjects(RDF.type, AOA.Attestation)}
        events = []
        for b in rows('SELECT ?i ?p ?pl WHERE { VALUES ?i { %s } VALUES ?p { wdt:P19 wdt:P20 } ?i ?p ?pl . FILTER(ISIRI(?pl)) }', set(people.values())):
            events.append((b['i']['value'].rsplit('/', 1)[1], 'born' if b['p']['value'].endswith('P19') else 'died', b['pl']['value'].rsplit('/', 1)[1]))
        new = sorted({pq for _, _, pq in events if pq not in known})
        coords, labels = {}, {}
        if new:
            # Countries, states and regions are not a place of birth to pin; direct P31 only, as P279* reaches "region" from cities.
            q = '''SELECT ?i ?c ?n WHERE { VALUES ?i { %s } ?i wdt:P625 ?c . OPTIONAL { ?i rdfs:label ?n FILTER(LANG(?n) = "en") }
                   FILTER NOT EXISTS { VALUES ?r { wd:Q6256 wd:Q3624078 wd:Q10864048 wd:Q12443800 wd:Q82794 wd:Q1620908 wd:Q3502482 wd:Q113406678 wd:Q34763 } ?i wdt:P31 ?r } }'''
            for b in rows(q, new):
                pq = b['i']['value'].rsplit('/', 1)[1]
                coords.setdefault(pq, b['c']['value'])
                if 'n' in b:
                    labels.setdefault(pq, b['n']['value'].replace('"', ''))
        for pq in new:
            if pq not in coords or pq not in labels:
                continue
            known[pq] = f':p_wd_{pq}'
            lines.append(f':p_wd_{pq} a aoa:Place ; rdfs:label "{labels[pq]}" ; aoa:placeKind aoa:place-city ; aoa:identification aoa:id-established ;\n'
                         f'    skos:exactMatch <{WD}{pq}> ; geo:hasGeometry [ geo:asWKT "{coords[pq]}"^^geo:wktLiteral ] ; aoa:modernName "{labels[pq]}" ;\n    {cite(pq)} .\n')
        byq = {q: s for s, q in people.items()}
        added = 0
        for qid, does, pq in sorted(events):
            who = local(byq[qid])
            if pq not in known or (who, does) in have:
                continue
            have.add((who, does))
            added += 1
            lines.append(f'[] a aoa:Attestation ; aoa:who {who} ; aoa:does aoa:at-{does} ; aoa:where {known[pq]} ;\n    {cite(qid)} .\n')
        print(f'birth and death places: {added} attestations, {sum(1 for pq in new if pq in known)} new places')
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT.relative_to(ROOT)}: {len(places)} places, {len(entries)} entries linked')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest='cmd', required=True)
    s = sub.add_parser('search', help='print candidate Wikidata ids for each name')
    s.add_argument('names', nargs='+')
    s.add_argument('--limit', type=int, default=5)
    s.add_argument('--coords', action='store_true', help='also show each candidate\'s coordinates')
    sub.add_parser('fetch', help=f'write {OUT.relative_to(ROOT)} from every Wikidata exactMatch or closeMatch')
    args = ap.parse_args()
    search(args.names, args.limit, args.coords) if args.cmd == 'search' else fetch()


if __name__ == '__main__':
    main()
